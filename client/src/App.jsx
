import React, { useState } from 'react';
import { Sparkles, Play, Table, Download } from 'lucide-react';

const INITIAL_ROWS = 15;
const INITIAL_COLS = 8;

export default function App() {
  const [grid, setGrid] = useState(
    Array(INITIAL_ROWS).fill(null).map(() => Array(INITIAL_COLS).fill(''))
  );
  const [prompt, setPrompt] = useState('');
  const [isLoading, setIsLoading] = useState(false);

  const handleCellChange = (rowIndex, colIndex, value) => {
    const updated = grid.map((row, rIdx) =>
      rIdx === rowIndex
        ? row.map((cell, cIdx) => (cIdx === colIndex ? value : cell))
        : row
    );
    setGrid(updated);
  };

  const handleRunAI = async () => {
    if (!prompt.trim()) return;
    setIsLoading(true);

    try {
      const res = await fetch('http://localhost:8000/api/v1/process-prompt', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          instruction: prompt,
          grid_data: grid,
        }),
      });
      const data = await res.json();
      if (data.updated_data) {
        setGrid(data.updated_data);
      }
    } catch (err) {
      console.error('Failed to execute AI instruction:', err);
    } finally {
      setIsLoading(false);
    }
  };

  const getColLabel = (index) => String.fromCharCode(65 + index);

  return (
    <div className="flex flex-col h-screen bg-slate-900 text-slate-100">
      {/* Top Header */}
      <header className="flex items-center justify-between px-6 py-3 border-b border-slate-800 bg-slate-950">
        <div className="flex items-center gap-2">
          <Table className="w-6 h-6 text-emerald-400" />
          <h1 className="font-semibold text-lg tracking-wide">Ai xlcex</h1>
          <span className="text-xs px-2 py-0.5 rounded bg-emerald-950 text-emerald-400 border border-emerald-800">
            v0.1.0-alpha
          </span>
        </div>
        <button className="flex items-center gap-2 px-3 py-1.5 text-sm bg-slate-800 hover:bg-slate-700 rounded-md border border-slate-700">
          <Download className="w-4 h-4" /> Export CSV
        </button>
      </header>

      {/* AI Prompt Bar */}
      <div className="p-4 bg-slate-900 border-b border-slate-800 flex gap-3 items-center">
        <div className="relative flex-1">
          <Sparkles className="absolute left-3 top-2.5 w-4 h-4 text-emerald-400" />
          <input
            type="text"
            value={prompt}
            onChange={(e) => setPrompt(e.target.value)}
            placeholder="Ask AI to calculate, clean data, or generate formulas (e.g., 'Calculate total sum in Column C')..."
            className="w-full pl-9 pr-4 py-2 bg-slate-950 border border-slate-700 rounded-lg text-sm focus:outline-none focus:border-emerald-500"
          />
        </div>
        <button
          onClick={handleRunAI}
          disabled={isLoading}
          className="flex items-center gap-2 px-4 py-2 bg-emerald-600 hover:bg-emerald-500 disabled:opacity-50 text-white rounded-lg text-sm font-medium transition-colors"
        >
          <Play className="w-4 h-4" />
          {isLoading ? 'Processing...' : 'Run'}
        </button>
      </div>

      {/* Grid Container */}
      <div className="flex-1 overflow-auto p-4 bg-slate-950">
        <div className="inline-block border border-slate-800 rounded">
          {/* Column Headers */}
          <div className="flex bg-slate-900 sticky top-0 z-10 border-b border-slate-800">
            <div className="w-12 h-8 border-r border-slate-800 flex items-center justify-center text-xs text-slate-500 font-mono">
              #
            </div>
            {grid[0].map((_, cIdx) => (
              <div
                key={cIdx}
                className="w-28 h-8 border-r border-slate-800 flex items-center justify-center text-xs font-semibold text-slate-400 font-mono"
              >
                {getColLabel(cIdx)}
              </div>
            ))}
          </div>

          {/* Table Rows */}
          {grid.map((row, rIdx) => (
            <div key={rIdx} className="flex border-b border-slate-900">
              <div className="w-12 h-8 border-r border-slate-800 bg-slate-900/60 flex items-center justify-center text-xs text-slate-500 font-mono select-none">
                {rIdx + 1}
              </div>
              {row.map((cell, cIdx) => (
                <input
                  key={cIdx}
                  type="text"
                  value={cell}
                  onChange={(e) => handleCellChange(rIdx, cIdx, e.target.value)}
                  className="w-28 h-8 px-2 border-r border-slate-800/80 bg-transparent text-xs text-slate-200 focus:bg-slate-800 focus:outline-none focus:ring-1 focus:ring-emerald-500"
                />
              ))}
            </div>
          ))}
        </div>
      </div>
    </div>
  );
}
