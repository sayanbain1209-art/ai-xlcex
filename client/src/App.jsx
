import React, { useState } from 'react';
import { Sparkles, Play, Table, Download, Trash2, HelpCircle } from 'lucide-react';

const INITIAL_ROWS = 15;
const INITIAL_COLS = 8;

export default function App() {
  const [grid, setGrid] = useState(
    Array(INITIAL_ROWS).fill(null).map(() => Array(INITIAL_COLS).fill(''))
  );
  const [prompt, setPrompt] = useState('');
  const [activeCell, setActiveCell] = useState({ r: 0, c: 0 });
  const [formulaSuggested, setFormulaSuggested] = useState('');
  const [explanation, setExplanation] = useState('');
  const [isLoading, setIsLoading] = useState(false);

  const getColLabel = (index) => String.fromCharCode(65 + index);

  const handleCellChange = (rowIndex, colIndex, value) => {
    const updated = grid.map((row, rIdx) =>
      rIdx === rowIndex
        ? row.map((cell, cIdx) => (cIdx === colIndex ? value : cell))
        : row
    );
    setGrid(updated);
  };

  const handleClearGrid = () => {
    if (confirm('Are you sure you want to clear the entire grid?')) {
      setGrid(Array(INITIAL_ROWS).fill(null).map(() => Array(INITIAL_COLS).fill('')));
      setFormulaSuggested('');
      setExplanation('');
    }
  };

  const handleExportCSV = () => {
    const csvContent = "data:text/csv;charset=utf-8," 
      + grid.map(e => e.map(cell => `"${cell}"`).join(",")).join("\n");
    const encodedUri = encodeURI(csvContent);
    const link = document.createElement("a");
    link.setAttribute("href", encodedUri);
    link.setAttribute("download", "ai_xlcex_export.csv");
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  const handleRunAI = async () => {
    if (!prompt.trim()) return;
    setIsLoading(true);
    setExplanation('AI is computing...');

    try {
      const res = await fetch('http://localhost:8000/api/v1/process-prompt', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          instruction: prompt,
          grid_data: grid,
        }),
      });
      const data = await res.json();
      if (data.updated_data) {
        setGrid(data.updated_data);
      }
      if (data.formula_suggested) {
        setFormulaSuggested(data.formula_suggested);
      }
      if (data.explanation) {
        setExplanation(data.explanation);
      }
    } catch (err) {
      console.error('Failed to execute AI instruction:', err);
      setExplanation('Error communicating with backend service.');
    } finally {
      setIsLoading(false);
    }
  };

  const activeValue = grid[activeCell.r]?.[activeCell.c] ?? '';

  return (
    <div className="flex flex-col h-screen bg-slate-900 text-slate-100 font-sans">
      {/* Top Navbar */}
      <header className="flex items-center justify-between px-6 py-3 border-b border-slate-800 bg-slate-950">
        <div className="flex items-center gap-3">
          <div className="p-1.5 bg-emerald-500/10 border border-emerald-500/20 rounded-lg">
            <Table className="w-5 h-5 text-emerald-400"/>
          </div>
          <div>
            <h1 className="font-semibold text-base leading-tight">Ai xlcex</h1>
            <span className="text-[10px] text-emerald-400 font-mono tracking-wider">AI SPREADSHEET ENGINE</span>
          </div>
        </div>

        <div className="flex items-center gap-2">
          <button
            onClick={handleClearGrid}
            className="flex items-center gap-1.5 px-3 py-1.5 text-xs text-rose-400 hover:bg-rose-950/40 rounded border border-rose-900/50 transition-colors"
          >
            <Trash2 className="w-3.5 h-3.5"/> Clear
          </button>
          <button
            onClick={handleExportCSV}
            className="flex items-center gap-1.5 px-3 py-1.5 text-xs bg-slate-800 hover:bg-slate-700 rounded border border-slate-700 transition-colors"
          >
            <Download className="w-3.5 h-3.5"/> Export CSV
          </button>
        </div>
      </header>

      {/* AI Prompt Input Bar */}
      <div className="p-3 bg-slate-900 border-b border-slate-800 flex gap-2 items-center">
        <div className="relative flex-1">
          <Sparkles className="absolute left-3 top-2.5 w-4 h-4 text-emerald-400"/>
          <input
            type="text"
            value={prompt}
            onChange={(e) => setPrompt(e.target.value)}
            onKeyDown={(e) => e.key === 'Enter' && handleRunAI()}
            placeholder="Instruction (e.g. 'Sum Column A', 'সব সংখ্যার যোগফল বের করো', 'Sort by B')..."
            className="w-full pl-9 pr-4 py-2 bg-slate-950 border border-slate-800 rounded-lg text-xs md:text-sm focus:outline-none focus:border-emerald-500 placeholder-slate-500"
          />
        </div>
        <button
          onClick={handleRunAI}
          disabled={isLoading}
          className="flex items-center gap-1.5 px-4 py-2 bg-emerald-600 hover:bg-emerald-500 disabled:opacity-50 text-white rounded-lg text-xs md:text-sm font-medium transition-colors"
        >
          <Play className="w-3.5 h-3.5 fill-current"/>
          {isLoading ? 'Running...' : 'Run'}
        </button>
      </div>

      {/* Formula Bar & Info Line */}
      <div className="px-4 py-2 bg-slate-950 border-b border-slate-800/80 flex items-center gap-4 text-xs">
        <div className="flex items-center gap-1 font-mono text-slate-400 border-r border-slate-800 pr-3">
          <span className="text-emerald-400 font-bold">{getColLabel(activeCell.c)}{activeCell.r + 1}</span>
        </div>
        <input
          type="text"
          value={activeValue}
          onChange={(e) => handleCellChange(activeCell.r, activeCell.c, e.target.value)}
          placeholder="Cell value or =FORMULA"
          className="flex-1 bg-transparent border-none text-slate-200 text-xs focus:outline-none font-mono"
        />
        {formulaSuggested && (
          <span className="text-emerald-400 bg-emerald-950/60 border border-emerald-800/60 px-2 py-0.5 rounded font-mono">
            {formulaSuggested}
          </span>
        )}
      </div>

      {/* Main Grid View */}
      <div className="flex-1 overflow-auto bg-slate-950 p-4">
        <div className="inline-block border border-slate-800 rounded shadow-sm bg-slate-900/30">
          {/* Column Header Row */}
          <div className="flex bg-slate-900 sticky top-0 z-10 border-b border-slate-800">
            <div className="w-10 h-7 border-r border-slate-800 flex items-center justify-center text-[11px] text-slate-500 font-mono">
              #
            </div>
            {grid[0].map((_, cIdx) => (
              <div
                key={cIdx}
                className="w-24 md:w-28 h-7 border-r border-slate-800 flex items-center justify-center text-[11px] font-semibold text-slate-400 font-mono"
              >
                {getColLabel(cIdx)}
              </div>
            ))}
          </div>

          {/* Table Cell Rows */}
          {grid.map((row, rIdx) => (
            <div key={rIdx} className="flex border-b border-slate-800/60">
              <div className="w-10 h-7 border-r border-slate-800 bg-slate-900/80 flex items-center justify-center text-[11px] text-slate-500 font-mono select-none">
                {rIdx + 1}
              </div>
              {row.map((cell, cIdx) => {
                const isSelected = activeCell.r === rIdx && activeCell.c === cIdx;
                return (
                  <input
                    key={cIdx}
                    type="text"
                    value={cell}
                    onFocus={() => setActiveCell({ r: rIdx, c: cIdx })}
                    onChange={(e) => handleCellChange(rIdx, cIdx, e.target.value)}
                    className={`w-24 md:w-28 h-7 px-2 border-r border-slate-800/60 bg-transparent text-xs text-slate-200 transition-colors font-mono focus:outline-none ${
                      isSelected
                        ? 'bg-emerald-950/40 ring-1 ring-emerald-500'
                        : 'hover:bg-slate-800/40'
                    }`}
                  />
                );
              })}
            </div>
          ))}
        </div>
      </div>

      {/* Bottom Status Bar */}
      <div className="px-4 py-2 bg-slate-950 border-t border-slate-800 text-[11px] text-slate-400 flex items-center justify-between">
        <div className="flex items-center gap-2">
          <HelpCircle className="w-3.5 h-3.5 text-slate-500"/>
          <span>{explanation || 'Ready. Click any cell to edit or enter an AI prompt above.'}</span>
        </div>
        <span className="text-slate-600 font-mono">UTF-8</span>
      </div>
    </div>
  );
}
